// Exports a recorded run as a basic Playwright test. Secrets become process.env lookups; targets use
// role + accessible name (or the test id when one was recorded).
import type { Predicate, TaskSpec } from "@ghosthand/protocol";
import type { ReplayStep } from "./replay.ts";

const q = (s: string): string => JSON.stringify(s);

function locator(step: ReplayStep): string | undefined {
  const t = step.target;
  if (!t) return undefined;
  if (t.automationId) return `page.getByTestId(${q(t.automationId)})`;
  return `page.getByRole(${q(t.role)} as Parameters<Page["getByRole"]>[0], { name: ${q(t.name)}, exact: true })`;
}

function actionLine(step: ReplayStep): string {
  const loc = locator(step);
  const a = step.action;
  switch (a.type) {
    case "press":
      return loc ? `await ${loc}.click();` : "// press: no target recorded";
    case "set_value":
    case "fill_credential": {
      const value =
        a.type === "fill_credential"
          ? `process.env[${q(a.name)}] ?? ""`
          : typeof a.value === "string"
            ? q(a.value)
            : `process.env[${q(a.value.secretRef)}] ?? ""`;
      return loc ? `await ${loc}.fill(${value});` : "// set_value: no target recorded";
    }
    case "toggle":
      return loc
        ? `await ${loc}.${a.checked === false ? "uncheck" : "check"}();`
        : "// toggle: no target recorded";
    case "select_option":
      return loc
        ? `await ${loc}.selectOption({ label: ${q(a.option)} });`
        : "// select_option: no target recorded";
    case "select_text":
      return loc
        ? `await ${loc}.evaluate((el, t) => { const r = document.createRange(); const w = document.createTreeWalker(el, NodeFilter.SHOW_TEXT); for (let n = w.nextNode(); n; n = w.nextNode()) { const i = (n as Text).data.indexOf(t); if (i >= 0) { r.setStart(n, i); r.setEnd(n, i + t.length); getSelection()?.removeAllRanges(); getSelection()?.addRange(r); return; } } }, ${q(a.text)});`
        : "// select_text: no target recorded";
    case "focus":
      return loc ? `await ${loc}.focus();` : "// focus";
    case "scroll_into_view":
      return loc ? `await ${loc}.scrollIntoViewIfNeeded();` : "// scroll";
    case "navigate":
      return `await page.goto(${q(a.url)});`;
    case "back":
      return "await page.goBack();";
    case "key":
      return `await page.keyboard.press(${q(a.keys.join("+"))});`;
    case "type_text":
      return `await page.keyboard.type(${typeof a.text === "string" ? q(a.text) : `process.env[${q(a.text.secretRef)}] ?? ""`});`;
    case "wait":
      return `await page.waitForTimeout(${a.ms});`;
    default:
      return `// ${a.type}: coordinate actions are not exported`;
  }
}

function expectLine(p: Predicate): string | undefined {
  switch (p.kind) {
    case "url":
      return p.matches.startsWith("/") && !p.matches.endsWith("/")
        ? `await expect(page).toHaveURL(new RegExp(${q(`${p.matches.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}/?$`)}));`
        : `await expect(page).toHaveURL(${p.matches.startsWith("/") ? `new RegExp(${q(p.matches.slice(1, -1))})` : q(p.matches)});`;
    case "visible":
      return p.role
        ? `await expect(page.getByRole(${q(p.role)} as Parameters<Page["getByRole"]>[0], { name: ${q(p.name)} })).toBeVisible();`
        : `await expect(page.getByText(${q(p.name)})).toBeVisible();`;
    case "text":
      return `await expect(page.getByText(${q(p.text)}).first()).toBeVisible();`;
    case "value":
      return `await expect(page.getByLabel(${q(p.name)})).toHaveValue(${q(p.value)});`;
    default:
      return undefined;
  }
}

export function exportPlaywrightSpec(task: TaskSpec, steps: ReplayStep[]): string {
  const checks = (task.plan?.subgoals ?? [])
    .flatMap((g) => g.doneWhen.all)
    .map(expectLine)
    .filter((l) => l !== undefined);
  const negatives = (task.plan?.subgoals ?? [])
    .flatMap((g) => g.doneWhen.none)
    .map((p) =>
      p.kind === "text" ? `await expect(page.getByText(${q(p.text)})).toHaveCount(0);` : undefined,
    )
    .filter((l) => l !== undefined);
  const secrets = [...new Set(task.secrets)];
  return [
    "// SPDX-License-Identifier: AGPL-3.0-only",
    `// Generated by GhostHand from a recorded run of ${task.id}. Review before committing.`,
    ...(secrets.length ? [`// Requires env: ${secrets.join(", ")}`] : []),
    'import { expect, type Page, test } from "@playwright/test";',
    "",
    `test(${q(`${task.id}: ${task.instruction}`)}, async ({ page }) => {`,
    `  await page.goto(${q(task.startUrl)});`,
    ...steps.map((s) => `  ${actionLine(s)}`),
    ...checks.map((l) => `  ${l}`),
    ...negatives.map((l) => `  ${l}`),
    "});",
    "",
  ].join("\n");
}
